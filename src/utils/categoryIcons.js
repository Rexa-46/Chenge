export function guessIconKey(name) {
  const n = norm(name);
  if (!n) return null;
  for (const [re, key] of RULES) if (ICONS[key] && re.test(n)) return key;
  return null;
}
// آیکن مؤثر: انتخاب خودِ کاربر ← حدس از نام ← (برای زیرمجموعه) آیکنِ والد
export function effectiveIconKey(c, categories = []) {
  if (c?.icon && ICONS[c.icon]) return c.icon;
  let cur = c, guard = 0;
  while (cur && guard++ < 8) {
    if (cur.icon && ICONS[cur.icon]) return cur.icon;
    const k = guessIconKey(cur.name);
    if (k) return k;
    cur = categories.find((x) => x.id === cur.parentId);
  }
  return null;
}
export const categoryIconOf = (c, categories = []) => ICONS[effectiveIconKey(c, categories)] || categoryIconFor(c?.name || "");
export const iconByKeyOrName = (key, name) => (key && ICONS[key]) || ICONS[guessIconKey(name)] || categoryIconFor(name || "");
